set
  capabilities_json =
    case
      when platform = 'instagram_reels'
        then coalesce(capabilities_json,'{}'::jsonb)
             || '{"publish":true}'::jsonb

      when platform = 'youtube_shorts'
        then coalesce(capabilities_json,'{}'::jsonb)
             || '{"publish":true,"analytics":true}'::jsonb

      when platform = 'tiktok_video'
        then coalesce(capabilities_json,'{}'::jsonb)
             || '{"publish":true}'::jsonb

      else coalesce(capabilities_json,'{}'::jsonb)
    end,
  updated_at = now();

