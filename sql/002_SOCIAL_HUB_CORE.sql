-- ------------------------------------------------------------
-- 9. Unified Social Inbox view
-- ------------------------------------------------------------
create or replace view public.v_social_inbox
with (security_invoker = true)
as
select
  sc.id as conversation_id,
  sc.platform,
  sc.status,
  sc.unread_count,
  sc.last_message_at,
  sc.last_inbound_at,
  sc.last_outbound_at,
  sc.labels,
  sc.account_id,
  ca.username as account_username,
  ca.display_name as account_display_name,
  c.id as contact_id,
  c.username as contact_username,
  c.display_name as contact_display_name,
  c.email,
  c.phone,
  c.lead_status,
  sc.source_history_id,
  sc.source_external_post_id,
  lm.body as last_message,
  lm.direction as last_direction,
  lm.message_type as last_message_type
from public.social_conversations sc
join public.content_accounts ca
  on ca.id = sc.account_id
join public.social_contacts c
  on c.id = sc.contact_id
left join lateral (
  select
    m.body,
    m.direction,
    m.message_type
  from public.social_messages m
  where m.conversation_id = sc.id
  order by m.sent_at desc, m.created_at desc
  limit 1
) lm on true;

-- ------------------------------------------------------------
-- 10. Content performance view
-- Does NOT depend on content_assets / clip_variants schema.
-- ------------------------------------------------------------
create or replace view public.v_social_post_performance
with (security_invoker = true)
as
select
  h.id as history_id,
  h.campaign_id,
  h.asset_id,
  h.account_id,
  coalesce(ca.platform, h.platform) as platform,
  ca.username,
  h.external_post_id,
  h.external_post_url,
  h.caption,
  h.created_at as published_at,

  coalesce(m.views, 0) as views,
  coalesce(m.likes, 0) as likes,
  coalesce(m.comments, 0) as comments,
  coalesce(m.shares, 0) as shares,
  coalesce(m.saves, 0) as saves,

  coalesce(clicks.clicks, 0) as link_clicks,
  coalesce(conv.conversations, 0) as conversations,
  coalesce(leads.leads, 0) as leads

from public.content_history h

left join public.content_accounts ca
  on ca.id = h.account_id

left join lateral (
  select
    p.views,
    p.likes,
    p.comments,
    p.shares,
    p.saves
  from public.post_metrics_snapshots p
  where p.history_id = h.id
  order by p.captured_at desc
  limit 1
) m on true

left join lateral (
  select count(*)::bigint as clicks
  from public.tracked_links l
  join public.tracked_link_clicks c
    on c.tracked_link_id = l.id
  where l.history_id = h.id
) clicks on true

left join lateral (
  select count(*)::bigint as conversations
  from public.social_conversations sc
  where sc.source_history_id = h.id
) conv on true

left join lateral (
  select count(*)::bigint as leads
  from public.growth_events ge
  where ge.history_id = h.id
    and ge.event_type in (
      'lead_captured',
      'webinar_registered',
      'call_booked',
      'client_won'
    )
) leads on true

where
  h.external_post_id is not null
  or h.status = 'published';

