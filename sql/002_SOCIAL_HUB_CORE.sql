-- 11. Claim pending replies for n8n worker
-- ------------------------------------------------------------
create or replace function public.claim_social_outbox(
  p_worker text,
  p_limit integer default 10
)
returns setof public.social_outbox
language plpgsql
security invoker
set search_path = public
as $$
begin
  return query

  with picked as (
    select o.id
    from public.social_outbox o
    where o.status = 'pending'
      and o.attempts < o.max_attempts
    order by o.queued_at asc
    for update skip locked
    limit greatest(1, least(coalesce(p_limit,10),50))
  )

  update public.social_outbox o
  set
    status = 'sending',
    attempts = o.attempts + 1,
    locked_at = now(),
    locked_by = p_worker,
    updated_at = now()
  from picked
  where o.id = picked.id
  returning o.*;
end;
$$;

