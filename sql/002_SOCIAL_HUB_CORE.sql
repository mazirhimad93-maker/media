-- ------------------------------------------------------------
-- 1. Metrics table used by Content Performance
-- ------------------------------------------------------------
create table if not exists public.post_metrics_snapshots (
  id bigint generated by default as identity primary key,
  history_id uuid not null,
  captured_at timestamptz not null default now(),
  views bigint not null default 0,
  likes bigint not null default 0,
  comments bigint not null default 0,
  shares bigint not null default 0,
  saves bigint not null default 0,
  watch_time_seconds numeric,
  raw_json jsonb not null default '{}'::jsonb
);

create index if not exists post_metrics_snapshots_history_captured_idx
  on public.post_metrics_snapshots(history_id, captured_at desc);

-- ------------------------------------------------------------
-- 2. Social contacts
-- ------------------------------------------------------------
create table if not exists public.social_contacts (
  id uuid primary key default gen_random_uuid(),
  platform text not null,
  platform_user_id text not null,
  username text,
  display_name text,
  email text,
  phone text,
  lead_status text not null default 'new'
    check (lead_status in (
      'new','engaged','qualified','registered',
      'booked','client','not_fit','archived'
    )),
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(platform, platform_user_id)
);

-- ------------------------------------------------------------
-- 3. Social conversations
-- ------------------------------------------------------------
create table if not exists public.social_conversations (
  id uuid primary key default gen_random_uuid(),
  account_id uuid not null references public.content_accounts(id) on delete cascade,
  contact_id uuid not null references public.social_contacts(id) on delete cascade,
  platform text not null,
  platform_thread_id text not null,
  source_history_id uuid,
  source_external_post_id text,
  status text not null default 'open'
    check (status in ('open','pending','qualified','booked','closed','archived')),
  unread_count integer not null default 0 check (unread_count >= 0),
  assigned_to text,
  human_takeover boolean not null default true,
  labels text[] not null default '{}'::text[],
  last_message_at timestamptz,
  last_inbound_at timestamptz,
  last_outbound_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(account_id, platform_thread_id)
);

create index if not exists social_conversations_account_idx
  on public.social_conversations(account_id);

create index if not exists social_conversations_contact_idx
  on public.social_conversations(contact_id);

create index if not exists social_conversations_last_message_idx
  on public.social_conversations(last_message_at desc);

-- ------------------------------------------------------------
-- 4. Messages
-- ------------------------------------------------------------
create table if not exists public.social_messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.social_conversations(id) on delete cascade,
  account_id uuid not null references public.content_accounts(id) on delete cascade,
  contact_id uuid not null references public.social_contacts(id) on delete cascade,
  platform_message_id text,
  direction text not null check (direction in ('inbound','outbound')),
  sender_role text not null default 'lead'
    check (sender_role in ('lead','account','system')),
  message_type text not null default 'text',
  body text,
  media_url text,
  in_reply_to_platform_message_id text,
  delivery_status text not null default 'received'
    check (delivery_status in (
      'received','queued','sent','delivered','read','failed'
    )),
  sent_at timestamptz not null default now(),
  raw_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create unique index if not exists social_messages_platform_mid_uidx
  on public.social_messages(account_id, platform_message_id)
  where platform_message_id is not null;

create index if not exists social_messages_conversation_sent_idx
  on public.social_messages(conversation_id, sent_at desc);

-- ------------------------------------------------------------
-- 5. Manual reply outbox
-- ------------------------------------------------------------
create table if not exists public.social_outbox (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.social_conversations(id) on delete cascade,
  account_id uuid not null references public.content_accounts(id) on delete cascade,
  contact_id uuid not null references public.social_contacts(id) on delete cascade,
  reply_mode text not null default 'dm'
    check (reply_mode in ('dm','comment_reply','private_reply')),
  target_platform_id text,
  body text not null,
  status text not null default 'pending'
    check (status in ('pending','sending','sent','failed','cancelled')),
  attempts integer not null default 0,
  max_attempts integer not null default 5,
  platform_message_id text,
  last_error text,
  locked_at timestamptz,
  locked_by text,
  queued_at timestamptz not null default now(),
  sent_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists social_outbox_pending_idx
  on public.social_outbox(status, queued_at)
  where status in ('pending','failed');

